"""Probe only a fresh, unlaunched debug sandbox. No wallet/LC initialization.

Install the inspected APK on the designated disposable emulator separately.
This command leaves Pocket disabled and refuses any initialized wallet state.
"""
import argparse
import subprocess
import uuid
import h02_package as policy
from h02_device import Device, REMOTE_ROOT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--serial', required=True)
    parser.add_argument('--apk-sha256', required=True)
    args = parser.parse_args()
    device = Device(args.serial, args.apk_sha256)
    device.stopped()
    absent = ('databases/pocket_node.db', 'shared_prefs/ckb_wallet_prefs.xml',
              'shared_prefs/ckb_pin_prefs.xml', 'files/key_backups',
              'files/data/testnet/store.db', 'files/data/mainnet/store.db')
    for path in absent:
        device.sandbox('test', '!', '-e', REMOTE_ROOT + '/' + path)
    device.freeze()
    try:
        device.sandbox('test', '-e', REMOTE_ROOT + '/databases/pocket_node.db')
    except policy.Refused:
        pass
    else:
        raise policy.Refused('remote-failure-status-lost')
    device.deploy()
    device.helper('probe', REMOTE_ROOT + '/files/h02-probe-' + uuid.uuid4().hex[:16])
    # Generated byte-transfer fixture only; not a Room/native wallet database.
    transfer = REMOTE_ROOT + '/files/h02-inspect-' + uuid.uuid4().hex[:16]
    device.sandbox('mkdir', '-m', '700', transfer)
    payload = bytes(range(256)) * 257
    device.put(transfer + '/app.json', payload)
    policy.require(device.get(transfer + '/app.json') == payload, 'binary-roundtrip')
    try:
        device.put(transfer + '/app.json', b'not-allowed-to-overwrite')
    except policy.Refused:
        pass
    else:
        raise policy.Refused('overwrite-was-accepted')
    policy.require(device.get(transfer + '/app.json') == payload, 'overwrite-changed-bytes')
    for path in absent:
        device.sandbox('test', '!', '-e', REMOTE_ROOT + '/' + path)
    print('EMPTY_SANDBOX_PROBE_PASS; run-as helper, synthetic SQLite/WAL, all-byte roundtrip, remote failure and overwrite refusal verified; no Pocket/LC launch; Pocket remains disabled')


if __name__ == '__main__':
    try:
        main()
    except (policy.Refused, ValueError, KeyError, TypeError, OSError, subprocess.SubprocessError):
        print('EMPTY_SANDBOX_PROBE_REFUSED')
        raise SystemExit(2)
